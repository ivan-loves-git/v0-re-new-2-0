export type UiCopyKey = keyof typeof uiFrench

export function uiCopy(language: Language, key: UiCopyKey): string {
  return language === "fr" ? uiFrench[key] : key
}

export function uiCopyWith(
  language: Language,
  key: UiCopyKey,
  values: Record<string, string | number>,
): string {
  return uiCopy(language, key).replace(/\{([a-zA-Z]+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  )
}
